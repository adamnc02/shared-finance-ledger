// Delete-reassign flows (PROMPT-05, 2026-09-16) — RESTRICT semantics for
// deleting a Person, a Pot or a Savings Pot (DECISIONS-2026-09-15.md Q5).
//
// Deleting any of the three is BLOCKED while anything still points at it.
// `findDeleteBlockers` lists what; `applyBlockerAction` resolves one item by
// reassigning it to an explicit, user-chosen target (never "the primary
// person") or deleting it. The Person/Pot/Savings Pot itself is only removed
// once the list is empty — see DeleteBlockedModal.
//
// Deliberately NOT restricted (Q5 items 3–4):
//  - CLEARED transactions are historical fact (APP-KNOWLEDGE §1.1). They
//    keep their ownerId/personId/potId/savingsPotId/fromLocation/toLocation
//    exactly as they are, and never block anything. `ON DELETE SET NULL` at
//    the database layer, later.
//  - Pending rows GENERATED by something (sourceType set, or a card's
//    minimum charge) follow their generator: reassigning the generator
//    rewrites them, deleting it sweeps them (lib/pendingSweep.ts). Only
//    hand-logged pending rows are listed individually.
//  - `locationHistory` entries are an audit trail, not live references.
//
// reconcilePersonReferences (lib/household.ts) stays the load-time
// self-healing backstop for imported/old data; this module is what stops
// the UI creating the dangling state in the first place.

