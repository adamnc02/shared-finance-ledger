// ── Salary Sort target removal (2026-09 session) — shared by
// updateTransaction (date-edit detach), removeTransaction (delete), and
// LedgerContext's own clearSalarySortTarget/saveSalarySort, so "drop one
// target, then remove the whole SalarySort if that empties it" is written
// exactly once. Pure — takes/returns the salarySorts array, no
// setDataState involved, so every caller composes it into their own
// single state update rather than this doing a second render pass.
// (Moved here from LedgerContext.tsx, which re-exports it.)
export function dropSalarySortTarget(salarySorts: SalarySort[], sortId: string, transactionId: string): SalarySort[] {
  return salarySorts
    .map((s) => (s.id === sortId ? { ...s, targets: s.targets.filter((t) => t.transactionId !== transactionId) } : s))
    .filter((s) => s.targets.length > 0)
}

// ── Plain removals — the state transforms behind LedgerContext's
// remove* mutations, shared with the blocker modal's "delete this item". ──

export function removeRecurringTemplateFromData(prev: AppDataV2, id: string, asOfIso: string = todayIso()): AppDataV2 {
  return {
    ...prev,
    recurringTemplates: prev.recurringTemplates.filter((t) => t.id !== id),
    transactions: sweepPendingForSource(prev.transactions, 'recurring_template', id, asOfIso),
  }
}

export function removeLoanFromData(prev: AppDataV2, id: string, asOfIso: string = todayIso()): AppDataV2 {
  const loan = prev.loans.find((l) => l.id === id)
  return {
    ...prev,
    loans: prev.loans.filter((l) => l.id !== id),
    transactions: loan ? sweepPendingForLoan(prev.transactions, loan, asOfIso) : prev.transactions,
  }
}

export function removeCreditCardFromData(prev: AppDataV2, id: string, asOfIso: string = todayIso()): AppDataV2 {
  return {
    ...prev,
    creditCards: prev.creditCards.filter((c) => c.id !== id),
    transactions: sweepPendingForCreditCard(prev.transactions, id, asOfIso),
  }
}

export function removePensionFromData(prev: AppDataV2, id: string, asOfIso: string = todayIso()): AppDataV2 {
  return {
    ...prev,
    pensions: prev.pensions.filter((p) => p.id !== id),
    transactions: sweepPendingForSource(prev.transactions, 'pension', id, asOfIso),
    // A person's followsIncomeSource pointing at a now-deleted pension
    // would silently strand their cycle-following choice — fall back
    // to 'salary' (the same default as never having set one), same
    // reconciliation instinct as household.ts's reconcilePersonReferences
    // for a dangling ownerId.
    payCycles: prev.payCycles.map((pc) =>
      pc.followsIncomeSource?.type === 'pension' && pc.followsIncomeSource.pensionId === id ? { ...pc, followsIncomeSource: { type: 'salary' } } : pc,
    ),
  }
}

export function removeTransactionFromData(prev: AppDataV2, id: string): AppDataV2 {
  const existing = prev.transactions.find((t) => t.id === id)
  const transactions = prev.transactions.filter((t) => t.id !== id)
  if (!existing || existing.sourceType !== 'salary_sort' || !existing.sourceId) {
    return { ...prev, transactions }
  }
  // Drops just this one target, leaving the rest of the sort intact
  // — matches saveSalarySort/clearSalarySortTarget's own "an empty
  // sort isn't a sort" rule if this was the last target.
  return { ...prev, transactions, salarySorts: dropSalarySortTarget(prev.salarySorts, existing.sourceId, id) }
}

export function removeLoanRecurringOverpaymentFromData(prev: AppDataV2, loanId: string, asOfIso: string = todayIso()): AppDataV2 {
  return {
    ...prev,
    loans: prev.loans.map((l) => (l.id === loanId ? { ...l, recurringOverpayment: undefined } : l)),
    transactions: prev.transactions.filter(
      (t) => !((t.status === 'pending' || t.date === asOfIso) && t.sourceType === 'loan_recurring_overpayment' && t.sourceId === loanId),
    ),
  }
}

export function removePersonFromData(prev: AppDataV2, id: string): AppDataV2 {
  if (prev.people.length <= 1) return prev // always at least one person
  const remaining = prev.people.filter((p) => p.id !== id)
  // With the delete guard in front of this, nothing should still point at
  // the person by now. reconcilePersonReferences still runs: it is what
  // turns a joint item into a personal one once fewer than 2 people are
  // left (Adam, 2026-09-16: joint bills reassigned at 100% move to
  // Personal when only one person remains), and it is the same backstop
  // every load/restore runs.
  return reconcilePersonReferences({
    ...prev,
    people: remaining,
    payCycles: prev.payCycles.filter((pc) => pc.personId !== id),
  })
}

export function removeSavingsPotFromData(prev: AppDataV2, id: string, asOfIso: string = todayIso()): AppDataV2 {
  // A pot's own CLEARED transactions (deposits/withdrawals/interest
  // already materialized) are historical fact and stay untouched —
  // same reasoning removePension uses for a person's past
  // pension_income transactions. PENDING ones are different: they
  // haven't happened yet and never will now, so they're swept
  // (2026-09 session — see sweepPendingForSavingsPot). The backstop then
  // clears anything else still pointing here (PROMPT-05 gaps 2–4), which
  // the delete guard should already have emptied.
  return reconcilePersonReferences({
    ...prev,
    savingsPots: prev.savingsPots.filter((p) => p.id !== id),
    transactions: sweepPendingForSavingsPot(prev.transactions, id, asOfIso),
  })
}

export function removePotFromData(prev: AppDataV2, id: string, asOfIso: string = todayIso()): AppDataV2 {
  return reconcilePersonReferences({
    ...prev,
    pots: prev.pots.filter((p) => p.id !== id),
    // A pot's own CLEARED transactions (deposits/withdrawals, and any
    // pot-funded bill/loan payment that already happened) are
    // historical fact and stay untouched — same reasoning
    // removeSavingsPot uses. PENDING ones are swept — they haven't
    // happened and never will now.
    transactions: sweepPendingForPot(prev.transactions, id, asOfIso),
    // Any bill/loan whose REGULAR payment pointed at this now-deleted
    // pot falls back to 'personal' rather than being left with a
    // dangling potId that nothing generates against. The delete guard
    // means the UI never reaches this with one still attached; kept for
    // any other caller. Recorded into locationHistory like any other
    // location change, so the Wallet page's audit trail shows WHY it moved.
    recurringTemplates: prev.recurringTemplates.map((t) =>
      t.location === 'pot' && t.potId === id
        ? {
            ...t,
            location: 'personal',
            potId: undefined,
            locationEffectiveFrom: asOfIso,
            locationHistory: [...(t.locationHistory ?? []), priorLocationEntry(t, t.anchorDate)],
          }
        : t,
    ),
    loans: prev.loans.map((l) => {
      let next = l
      if (l.location === 'pot' && l.potId === id) {
        next = {
          ...next,
          location: 'personal',
          potId: undefined,
          locationEffectiveFrom: asOfIso,
          locationHistory: [...(next.locationHistory ?? []), priorLocationEntry(next, next.startDate)],
        }
      }
      // A recurring overpayment independently funded from this pot
      // loses that explicit choice too — reverts to "follows the
      // loan's own location" (the field's own absent-default), not
      // forced to 'personal', since the loan itself might still be
      // pot-funded via a DIFFERENT pot, or genuinely personal/joint.
      if (next.recurringOverpayment?.location === 'pot' && next.recurringOverpayment.potId === id) {
        next = { ...next, recurringOverpayment: { ...next.recurringOverpayment, location: undefined, potId: undefined } }
      }
      return next
    }),
    // 2026-09-16 — a card whose minimum payment was paid from this pot.
    creditCards: prev.creditCards.map((c) => (c.location === 'pot' && c.potId === id ? relocateCreditCard(c, 'personal', undefined, asOfIso) : c)),
  })
}

